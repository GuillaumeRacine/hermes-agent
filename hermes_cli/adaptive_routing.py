"""Deterministic shadow and guarded routing for Hermes turns.

This module never invokes a model. It classifies task complexity/risk/privacy
using explicit rules, reads a quality-gated policy generated by the eval
harness, and emits secret-safe JSONL telemetry. ``shadow`` never changes the
runtime. ``guarded`` may select an optimizer-approved native Hermes runtime for
a new session/task epoch; callers must keep that route pinned for the epoch.
"""

